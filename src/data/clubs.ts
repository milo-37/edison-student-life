export function getClubBySlug(slug: string): Club | undefined {
  return clubs.find((c) => c.slug === slug);
}

export function getAdjacentClubs(slug: string): {
  prev: Club | null;
  next: Club | null;
} {
  const idx = clubs.findIndex((c) => c.slug === slug);
  return {
    prev: idx > 0 ? clubs[idx - 1] : clubs[clubs.length - 1],
    next: idx < clubs.length - 1 ? clubs[idx + 1] : clubs[0],
  };
}
